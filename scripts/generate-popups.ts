import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync
} from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const projectRoot = fileURLToPath(new URL('../', import.meta.url))

/** Shared naming rule with src-tauri/build_support/popups.rs. */
export function discoverPopups(root: string) {
  const definitions = new Map<string, string>()
  function visit(directory: string) {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name)
      if (entry.isDirectory()) visit(path)
      else if (entry.isFile() && /\.popup\.tsx?$/.test(entry.name)) {
        const id = entry.name.replace(/\.popup\.tsx?$/, '')
        if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id)) {
          throw new Error(`Invalid popup ID '${id}': ${path}`)
        }
        const previous = definitions.get(id)
        if (previous) {
          throw new Error(`Duplicate popup ID '${id}': ${previous} and ${path}`)
        }
        definitions.set(id, path)
      }
    }
  }
  visit(root)
  return [...definitions].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
}

export function generatePopups(root = projectRoot) {
  const output = resolve(root, 'src/popups/.generated/popups.ts')
  const definitions = discoverPopups(resolve(root, 'src/features'))
  const imports = definitions.map(([, path], index) => {
    const specifier = relative(dirname(output), path)
      .replaceAll('\\', '/')
      .replace(/\.tsx?$/, '')
    return `import popup${index} from ${JSON.stringify(specifier)}`
  })
  const entries = definitions.map(
    ([id], index) => `  [${JSON.stringify(id)}]: popup${index}`
  )
  const source = [
    '// Generated by scripts/generate-popups.ts. Do not edit.',
    ...imports,
    '',
    `export type PopupId = ${definitions.map(([id]) => JSON.stringify(id)).join(' | ') || 'never'}`,
    '',
    'export const discoveredPopups = {',
    entries.join(',\n'),
    '}',
    ''
  ].join('\n')
  if (existsSync(output) && readFileSync(output, 'utf8') === source)
    return false
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, source)
  return true
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  generatePopups()
}
